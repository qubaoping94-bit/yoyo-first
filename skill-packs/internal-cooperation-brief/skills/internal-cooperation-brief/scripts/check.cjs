'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),os=require('node:os');
const {normalize,render,generate}=require('./render.cjs');
const input={title:'虚构示例',focus:{lines:['整理本次需求，','明确推进安排。']},sections:[{title:'需求',status:'已收到',items:[{label:'资料',text:'<img src=x onerror=alert(1)> & "报价"',keepTogether:['"报价"']}]}]};
assert.throws(()=>normalize(null));
assert.throws(()=>normalize({...input,sections:[]}));
assert.throws(()=>normalize({...input,sections:[{title:'需求',items:[]}]}));
const result=render(input);
assert.ok(!result.html.includes('<img'));
assert.ok(result.html.includes('&lt;img'));
assert.ok(result.html.includes('&amp;'));
assert.equal(result.data.title,input.title);
assert.ok(result.html.includes('目前首要任务'));
assert.equal(result.data.sections[0].items[0].text,input.sections[0].items[0].text);
const root=process.argv[2]?path.resolve(process.argv[2]):os.tmpdir();fs.mkdirSync(root,{recursive:true});
const dir=fs.mkdtempSync(path.join(root,'brief-check-')),source=path.join(dir,'source.json'),out=path.join(dir,'output');
fs.writeFileSync(source,JSON.stringify(input));generate(source,out);
const before=fs.readFileSync(path.join(out,'report.html'));
assert.throws(()=>generate(source,out),/已存在/);
assert.deepEqual(fs.readFileSync(path.join(out,'report.html')),before);
console.log('PASS: schema validation, HTML escaping, source preservation, no case-data leakage, no-overwrite');
